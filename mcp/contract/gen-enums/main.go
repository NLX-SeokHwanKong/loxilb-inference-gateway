// gen-enums writes the swagger-derived tables the tools package compiles
// in: the property list of every request model the bridge builds, the enum
// values and descriptions of enumerated properties, and the excluded-field
// set of mcp/contract/fields.yml. Run through `go generate ./...` in mcp/;
// CI fails when the committed output differs.
//
// Usage:
//
//	go run ./contract/gen-enums -api ../api -fields contract/fields.yml -out internal/mcp/tools/zz_swagger_enums_gen.go
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"

	"github.com/loxilb-io/loxilb-inference-gateway/mcp/contract"
)

// models whose tables are emitted, in output order.
var models = []string{
	"serviceArguments", "endpoints", "ApiKeyCreateRequest", "TenantRateLimitMod",
	"UserRateLimitMod", "RateLimitDefaultsMod",
}

func main() {
	apiDir := flag.String("api", "", "gateway api/ directory holding swagger.yml and swagger-extras.yml")
	fieldsPath := flag.String("fields", "", "mcp/contract/fields.yml")
	out := flag.String("out", "", "generated Go file to write")
	flag.Parse()
	if *apiDir == "" || *fieldsPath == "" || *out == "" {
		fmt.Fprintln(os.Stderr, "gen-enums: -api, -fields and -out are required")
		os.Exit(2)
	}
	spec, err := contract.LoadSwagger(*apiDir)
	if err != nil {
		fmt.Fprintf(os.Stderr, "gen-enums: swagger: %v\n", err)
		os.Exit(2)
	}
	fields, err := contract.LoadFields(*fieldsPath)
	if err != nil {
		fmt.Fprintf(os.Stderr, "gen-enums: fields: %v\n", err)
		os.Exit(2)
	}
	src, err := render(spec, fields)
	if err != nil {
		fmt.Fprintf(os.Stderr, "gen-enums: %v\n", err)
		os.Exit(2)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "gen-enums: %v\n", err)
		os.Exit(2)
	}
}

func render(spec *contract.Spec, fields *contract.Fields) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by mcp/contract/gen-enums from api/swagger.yml and mcp/contract/fields.yml; DO NOT EDIT.\n\n")
	b.WriteString("package tools\n\n")

	b.WriteString("// swaggerProps lists the request-body properties of each model the bridge builds.\n")
	b.WriteString("var swaggerProps = map[string][]string{\n")
	for _, m := range models {
		props, ok := spec.Model(m)
		if !ok {
			return nil, fmt.Errorf("model %s not found in swagger", m)
		}
		fmt.Fprintf(&b, "\t%q: {", m)
		for i, p := range props {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%q", p.Name)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")

	b.WriteString("// swaggerEnum holds the permitted values of every enumerated property, keyed model.property.\n")
	b.WriteString("var swaggerEnum = map[string][]string{\n")
	for _, m := range models {
		props, _ := spec.Model(m)
		for _, p := range props {
			if p.Enum == nil {
				continue
			}
			fmt.Fprintf(&b, "\t%q: {", m+"."+p.Name)
			for i, v := range p.Enum {
				if i > 0 {
					b.WriteString(", ")
				}
				fmt.Fprintf(&b, "%q", v)
			}
			b.WriteString("},\n")
		}
	}
	b.WriteString("}\n\n")

	b.WriteString("// swaggerEnumDoc holds the swagger description of every enumerated property, keyed model.property.\n")
	b.WriteString("var swaggerEnumDoc = map[string]string{\n")
	for _, m := range models {
		props, _ := spec.Model(m)
		for _, p := range props {
			if p.Enum == nil {
				continue
			}
			fmt.Fprintf(&b, "\t%q: %q,\n", m+"."+p.Name, p.Description)
		}
	}
	b.WriteString("}\n\n")

	b.WriteString("// swaggerExcludedField lists the properties fields.yml marks excluded-field, keyed model.property, with the reason.\n")
	b.WriteString("var swaggerExcludedField = map[string]string{\n")
	excl := fields.Excluded()
	mnames := make([]string, 0, len(excl))
	for m := range excl {
		mnames = append(mnames, m)
	}
	sort.Strings(mnames)
	for _, m := range mnames {
		fnames := make([]string, 0, len(excl[m]))
		for f := range excl[m] {
			fnames = append(fnames, f)
		}
		sort.Strings(fnames)
		for _, f := range fnames {
			fmt.Fprintf(&b, "\t%q: %q,\n", m+"."+f, excl[m][f])
		}
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
