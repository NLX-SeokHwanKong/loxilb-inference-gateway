// gen-metricsdoc writes the generated half of the loxilb://docs/metrics
// resource: one table row per gateway metric family, as tools/metric-manifest
// finds them in the gateway source (name, type, label names, the first
// sentence of the help text). The curated half (key families, caveats) stays
// hand-written in resources.go. Run through `go generate ./...` in mcp/; CI
// fails when the committed output differs.
//
// The output is a _gen.go file, so the metric contract test does not count
// the table as the bridge referencing every family.
//
// Usage:
//
//	go run ./contract/gen-metricsdoc -root .. -out internal/mcp/zz_metrics_reference_gen.go
package main

import (
	"bytes"
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
	"time"
)

// helpMax bounds one row's help text; the full text is on the scrape
// (metrics_snapshot returns it per family).
const helpMax = 240

type def struct {
	Name       string   `json:"name"`
	Type       string   `json:"type"`
	Labels     []string `json:"labels"`
	Help       string   `json:"help"`
	Unresolved bool     `json:"unresolved"`
}

func main() {
	root := flag.String("root", "", "gateway repository root (holds tools/metric-manifest)")
	out := flag.String("out", "", "generated Go file to write")
	flag.Parse()
	if *root == "" || *out == "" {
		fmt.Fprintln(os.Stderr, "gen-metricsdoc: -root and -out are required")
		os.Exit(2)
	}
	if _, err := os.Stat(filepath.Join(*root, "tools", "metric-manifest", "main.go")); err != nil {
		fmt.Fprintf(os.Stderr, "gen-metricsdoc: %v\n", err)
		os.Exit(2)
	}
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Minute)
	defer cancel()
	cmd := exec.CommandContext(ctx, "go", "run", "./tools/metric-manifest", "-root", ".")
	cmd.Dir = *root
	cmd.Stderr = os.Stderr
	raw, err := cmd.Output()
	if err != nil {
		fmt.Fprintf(os.Stderr, "gen-metricsdoc: go run ./tools/metric-manifest: %v\n", err)
		os.Exit(2)
	}
	var defs []def
	if err := json.Unmarshal(raw, &defs); err != nil {
		fmt.Fprintf(os.Stderr, "gen-metricsdoc: metric-manifest output: %v\n", err)
		os.Exit(2)
	}
	src, err := render(defs)
	if err != nil {
		fmt.Fprintf(os.Stderr, "gen-metricsdoc: %v\n", err)
		os.Exit(2)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "gen-metricsdoc: %v\n", err)
		os.Exit(2)
	}
}

func render(defs []def) ([]byte, error) {
	// One row per family name: a family defined at two sites (a template
	// expanded twice, a collector and its Describe) is one family.
	byName := map[string]def{}
	other := map[string]bool{}
	for _, d := range defs {
		if d.Unresolved {
			continue
		}
		if !strings.HasPrefix(d.Name, "loxilb_") {
			other[d.Name] = true
			continue
		}
		if prev, ok := byName[d.Name]; ok && prev.Help != "" {
			continue
		}
		byName[d.Name] = d
	}
	names := make([]string, 0, len(byName))
	for n := range byName {
		names = append(names, n)
	}
	sort.Strings(names)

	var t strings.Builder
	fmt.Fprintf(&t, "## All gateway families (generated)\n\n")
	fmt.Fprintf(&t, "%d loxilb_* families, from tools/metric-manifest over the gateway source; the %d other "+
		"families it finds (the aictrl_* and doca_* ones) are outside the bridge's scope and not listed. "+
		"Type \"collector\" is a family a custom collector emits (its exposition TYPE line names the kind). "+
		"Help is the first sentence; metrics_snapshot returns the full text.\n\n", len(names), len(other))
	t.WriteString("| family | type | labels | help |\n|---|---|---|---|\n")
	for _, n := range names {
		d := byName[n]
		typ := d.Type
		if typ == "desc" {
			typ = "collector"
		}
		labels := append([]string(nil), d.Labels...)
		sort.Strings(labels)
		fmt.Fprintf(&t, "| %s | %s | %s | %s |\n", n, typ, cell(strings.Join(labels, ", ")), cell(firstSentence(d.Help)))
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by mcp/contract/gen-metricsdoc from tools/metric-manifest; DO NOT EDIT.\n\n")
	b.WriteString("package mcp\n\n")
	b.WriteString("// metricFamilyTable is the generated half of loxilb://docs/metrics.\n")
	fmt.Fprintf(&b, "const metricFamilyTable = %q\n", t.String())
	return format.Source(b.Bytes())
}

// firstSentence cuts a help text at its first ". " and at helpMax runes.
func firstSentence(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	if i := strings.Index(s, ". "); i >= 0 {
		s = s[:i+1]
	}
	if r := []rune(s); len(r) > helpMax {
		s = string(r[:helpMax-1]) + "…"
	}
	return s
}

// cell keeps a value inside one markdown table cell.
func cell(s string) string {
	if s == "" {
		return "-"
	}
	return strings.ReplaceAll(s, "|", `\|`)
}
